#!/usr/bin/env bash
# One-time OpenReply install for a fresh Ubuntu 24.04 Hetzner server.
# Run as root, from a terminal (Hetzner web console or SSH). Do not pipe this file into bash:
# prompts need the keyboard.
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/nvgii/openreply.git}"
BRANCH="${BRANCH:-main}"
APP_DIR="${APP_DIR:-/opt/openreply}"
ENV_FILE="$APP_DIR/deploy/hetzner/.env"

if [[ "$(id -u)" -ne 0 ]]; then
  echo "Bitte als root starten. In der Hetzner-Konsole zuerst: root"
  exit 1
fi

if [[ ! -t 0 ]]; then
  echo "Dieses Skript stellt Fragen und braucht die Tastatur."
  echo "Nicht mit curl | bash starten. Stattdessen:"
  echo "  curl -fsSL https://raw.githubusercontent.com/nvgii/openreply/${BRANCH}/deploy/hetzner/install.sh -o /tmp/openreply-install.sh && bash /tmp/openreply-install.sh"
  exit 1
fi

ask() {
  local __var="$1" __text="$2" __default="${3:-}" __value
  if [[ -n "$__default" ]]; then
    read -r -p "$__text [$__default]: " __value
    __value="${__value:-$__default}"
  else
    read -r -p "$__text: " __value
  fi
  # The Hetzner web console sometimes pastes a trailing carriage return.
  __value="${__value%$'\r'}"
  __value="${__value#"${__value%%[![:space:]]*}"}"
  __value="${__value%"${__value##*[![:space:]]}"}"
  printf -v "$__var" '%s' "$__value"
}

normalize_domain() {
  local value="$1"
  value="${value#https://}"
  value="${value#http://}"
  value="${value%%/*}"
  value="${value%/}"
  printf '%s' "$value"
}

echo "OpenReply: Docker, Firewall, Schlüssel, Start."
echo "Der erste Bau dauert mehrere Minuten."
echo

export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y ca-certificates curl git ufw openssl

mem_kb="$(awk '/MemTotal/ {print $2}' /proc/meminfo)"
if [[ "$mem_kb" -lt 6000000 ]] && ! swapon --show | grep -q .; then
  echo "Wenig Arbeitsspeicher. Lege 2 GB Auslagerung an, damit der Bau durchläuft."
  fallocate -l 2G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=2048 status=progress
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  grep -q '/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker

ufw allow OpenSSH
ufw allow 22/tcp
ufw allow 80/tcp
ufw allow 443/tcp
ufw --force enable

if [[ ! -d "$APP_DIR/.git" ]]; then
  git clone --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
else
  git -C "$APP_DIR" fetch origin "$BRANCH"
  git -C "$APP_DIR" checkout -B "$BRANCH" "origin/$BRANCH"
fi

cd "$APP_DIR/deploy/hetzner"

if [[ -f "$ENV_FILE" ]]; then
  echo
  echo "Die Datei $ENV_FILE gibt es schon. Vorhandene Schlüssel bleiben."
  echo "Meta-Werte später eintragen: bash $APP_DIR/deploy/hetzner/update.sh env"
  read -r -p "Container neu bauen und starten? [ja]: " again
  again="${again:-ja}"
  if [[ "$again" == "ja" || "$again" == "j" || "$again" == "y" || "$again" == "Y" ]]; then
    docker compose --env-file .env up -d --build
  fi
  exit 0
fi

ask DOMAIN "Domain oder Subdomain" "reply.nadworker.de"
DOMAIN="$(normalize_domain "$DOMAIN")"
if [[ ! "$DOMAIN" =~ ^[A-Za-z0-9.-]+$ ]]; then
  echo "Die Domain darf nur Buchstaben, Zahlen, Punkte und Bindestriche haben: $DOMAIN"
  exit 1
fi

ask ALLOWED_EMAILS "Login-E-Mail (nur diese Adresse darf sich anmelden)" "hello@nadworker.de"
ask RESEND_API_KEY "Resend API-Key (beginnt mit re_)"
while [[ -z "${RESEND_API_KEY}" ]]; do
  ask RESEND_API_KEY "Resend API-Key (beginnt mit re_)"
done
ask EMAIL_FROM "Absender der Login-Mail" "OpenReply <hello@nadworker.de>"

echo
echo "Meta-Werte kannst du jetzt eintragen oder später mit:"
echo "  bash $APP_DIR/deploy/hetzner/update.sh env"
ask INSTAGRAM_APP_ID "INSTAGRAM_APP_ID (leer lassen mit Enter)"
ask INSTAGRAM_APP_SECRET "INSTAGRAM_APP_SECRET (leer lassen mit Enter)"
ask FACEBOOK_APP_SECRET "FACEBOOK_APP_SECRET (leer lassen mit Enter)"

ACME_EMAIL="${ALLOWED_EMAILS%%,*}"
ACME_EMAIL="${ACME_EMAIL// /}"

ENCRYPTION_KEY="$(openssl rand -hex 32)"
NEXTAUTH_SECRET="$(openssl rand -hex 32)"
CRON_SECRET="$(openssl rand -hex 32)"
WEBHOOK_VERIFY_TOKEN="$(openssl rand -hex 32)"
POSTGRES_PASSWORD="$(openssl rand -hex 24)"
REDIS_PASSWORD="$(openssl rand -hex 24)"

umask 077
{
  printf '%s\n' "# Generated by deploy/hetzner/install.sh. chmod 600."
  printf '%s\n' "# Back up ENCRYPTION_KEY outside this server. Losing it means reconnecting Instagram."
  printf '\n'
  printf 'DOMAIN=%s\n' "$DOMAIN"
  printf 'ACME_EMAIL=%s\n' "$ACME_EMAIL"
  printf 'NEXTAUTH_URL=%s\n' "https://${DOMAIN}"
  printf 'NEXTAUTH_SECRET=%s\n' "$NEXTAUTH_SECRET"
  printf 'CRON_SECRET=%s\n' "$CRON_SECRET"
  printf 'CRON_BASE_URL=%s\n' "http://web:3000"
  printf 'ENCRYPTION_KEY=%s\n' "$ENCRYPTION_KEY"
  printf 'WEBHOOK_VERIFY_TOKEN=%s\n' "$WEBHOOK_VERIFY_TOKEN"
  printf '\n'
  printf 'POSTGRES_USER=%s\n' "openreply"
  printf 'POSTGRES_PASSWORD=%s\n' "$POSTGRES_PASSWORD"
  printf 'POSTGRES_DB=%s\n' "openreply"
  printf 'DATABASE_URL=%s\n' "postgresql://openreply:${POSTGRES_PASSWORD}@postgres:5432/openreply"
  printf '\n'
  printf 'REDIS_PASSWORD=%s\n' "$REDIS_PASSWORD"
  printf 'REDIS_URL=%s\n' "redis://:${REDIS_PASSWORD}@redis:6379?family=0"
  printf '\n'
  printf 'META_GRAPH_API_VERSION=%s\n' "v25.0"
  printf 'RESEND_API_KEY=%s\n' "$RESEND_API_KEY"
  printf 'EMAIL_FROM="%s"\n' "$EMAIL_FROM"
  printf 'ALLOWED_EMAILS=%s\n' "$ALLOWED_EMAILS"
  printf '\n'
  printf 'INSTAGRAM_APP_ID=%s\n' "$INSTAGRAM_APP_ID"
  printf 'INSTAGRAM_APP_SECRET=%s\n' "$INSTAGRAM_APP_SECRET"
  printf 'FACEBOOK_APP_SECRET=%s\n' "$FACEBOOK_APP_SECRET"
} > "$ENV_FILE"
chmod 600 "$ENV_FILE"

echo
echo "Baue und starte die Container. Das kann einige Minuten dauern."
docker compose --env-file .env up -d --build

echo
echo "============================================================"
echo "OpenReply läuft (oder der erste Start ist noch im Bau)."
echo
echo "Seite:    https://${DOMAIN}"
echo "Lebendig: https://${DOMAIN}/api/live"
echo "Gesund:   https://${DOMAIN}/api/health"
echo
echo "ENCRYPTION_KEY (jetzt woanders sichern, Passwort-Manager oder Papier):"
echo "${ENCRYPTION_KEY}"
echo
echo "WEBHOOK_VERIFY_TOKEN (denselben Text bei Meta einfügen):"
echo "${WEBHOOK_VERIFY_TOKEN}"
echo
echo "Beide Werte stehen auch in:"
echo "  ${ENV_FILE}"
echo "Ohne den ENCRYPTION_KEY musst du Instagram neu verbinden, auch wenn die Datenbank noch da ist."
echo "============================================================"
echo
echo "Zertifikat: die Domain muss per A-Eintrag auf diese Server-IP zeigen."
echo "Logs: cd ${APP_DIR}/deploy/hetzner && docker compose --env-file .env logs -f caddy web"
